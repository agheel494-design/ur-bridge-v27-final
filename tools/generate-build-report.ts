// ─────────────────────────────────────────────────────────────────────────────
// UR — Automated Build Report Generator
// Per explicit review request: eliminates manual test-count reporting,
// which was found wrong multiple times across this project's history
// (2024->2029, 2051->2060, 2117->2118, 159->160 optimizer tests) —
// every one of those corrections was a HAND-COUNTING error, never a
// real test failure. This tool is the fix: it is the only thing that
// ever produces these numbers from now on.
// ─────────────────────────────────────────────────────────────────────────────
//
// Run manually (or from CI): tsx tools/generate-build-report.ts [versionTag]
//
// Produces:
//   BUILD_REPORT.md          - human-readable, OVERWRITTEN each run
//   BUILD_REPORT_HISTORY.json - append-only, one entry per run

import { execSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const REPORT_MD_PATH = join(ROOT, "BUILD_REPORT.md");
const HISTORY_JSON_PATH = join(ROOT, "BUILD_REPORT_HISTORY.json");
const TSX = process.env.TSX_BIN ?? "tsx";

function findTestFiles(dir: string, out: string[] = []): string[] {
  for (const entry of readdirSync(dir)) {
    if (entry === "node_modules" || entry.startsWith(".")) continue;
    const full = join(dir, entry);
    const st = statSync(full);
    if (st.isDirectory()) findTestFiles(full, out);
    else if (entry.endsWith(".test.ts")) out.push(full);
  }
  return out;
}

interface FileResult {
  readonly file: string;
  readonly tests: number;
  readonly passed: number;
  readonly failed: number;
  readonly ok: boolean;
  readonly errorNote?: string;
}

function runOneTestFile(file: string): FileResult {
  const relative = file.replace(ROOT + "/", "");
  try {
    const output = execSync(`${TSX} run-tests.ts "${relative}"`, { cwd: ROOT, encoding: "utf-8", stdio: ["ignore", "pipe", "pipe"] });
    const testsMatch = output.match(/Tests:\s*(\d+)/);
    const passedMatch = output.match(/Passed:\s*(\d+)/);
    const failedMatch = output.match(/Failed:\s*(\d+)/);
    const tests = testsMatch ? Number(testsMatch[1]) : 0;
    const passed = passedMatch ? Number(passedMatch[1]) : 0;
    const failed = failedMatch ? Number(failedMatch[1]) : 0;
    if (/TransformError|Unexpected "/.test(output)) {
      return { file: relative, tests: 0, passed: 0, failed: 0, ok: false, errorNote: "TransformError/load failure" };
    }
    return { file: relative, tests, passed, failed, ok: failed === 0 && tests > 0 };
  } catch (e) {
    // A non-zero exit code from the test runner itself (real test failures propagate here for some runners).
    const output = e instanceof Error && "stdout" in e ? String((e as unknown as { stdout: Buffer }).stdout) : "";
    const testsMatch = output.match(/Tests:\s*(\d+)/);
    const passedMatch = output.match(/Passed:\s*(\d+)/);
    const failedMatch = output.match(/Failed:\s*(\d+)/);
    return {
      file: relative,
      tests: testsMatch ? Number(testsMatch[1]) : 0,
      passed: passedMatch ? Number(passedMatch[1]) : 0,
      failed: failedMatch ? Number(failedMatch[1]) : 1,
      ok: false,
      errorNote: "non-zero exit",
    };
  }
}

function gitCommitOrNA(): string {
  try {
    return execSync("git rev-parse HEAD", { cwd: ROOT, encoding: "utf-8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return "N/A (no git repository)";
  }
}

function main(): void {
  const versionTag = process.argv[2] ?? "untagged";
  const startedAt = new Date().toISOString();

  const testFiles = findTestFiles(join(ROOT, "tests"));
  const results: FileResult[] = [];
  for (const file of testFiles) {
    process.stdout.write(`Running ${file.replace(ROOT + "/", "")} ... `);
    const result = runOneTestFile(file);
    results.push(result);
    console.log(result.ok ? `OK (${result.tests})` : `FAIL/ERROR (${result.errorNote ?? `${result.failed} failed`})`);
  }

  const totalFiles = results.length;
  const totalTests = results.reduce((sum, r) => sum + r.tests, 0);
  const totalPassed = results.reduce((sum, r) => sum + r.passed, 0);
  const totalFailed = results.reduce((sum, r) => sum + r.failed, 0);
  const filesWithErrors = results.filter(r => !r.ok);

  const commit = gitCommitOrNA();
  const finishedAt = new Date().toISOString();

  // ── BUILD_REPORT.md (human-readable, overwritten each run) ──────────────
  const md: string[] = [];
  md.push("# UR Build Report");
  md.push("");
  md.push("**This file is auto-generated by `tools/generate-build-report.ts`.");
  md.push("Do not hand-edit any number in this file — regenerate it instead.**");
  md.push("");
  md.push(`- Version tag: \`${versionTag}\``);
  md.push(`- Git commit: \`${commit}\``);
  md.push(`- Generated at: ${finishedAt}`);
  md.push("");
  md.push("## Summary");
  md.push("");
  md.push(`- Test files: **${totalFiles}**`);
  md.push(`- Total tests: **${totalTests}**`);
  md.push(`- Passed: **${totalPassed}**`);
  md.push(`- Failed: **${totalFailed}**`);
  md.push(`- Files with errors/load failures: **${filesWithErrors.length}**`);
  md.push("");
  if (filesWithErrors.length > 0) {
    md.push("## Files With Errors");
    md.push("");
    for (const r of filesWithErrors) md.push(`- \`${r.file}\`: ${r.errorNote ?? `${r.failed} failed`}`);
    md.push("");
  }
  md.push("## Per-File Breakdown");
  md.push("");
  md.push("| File | Tests | Passed | Failed |");
  md.push("|---|---|---|---|");
  for (const r of results.sort((a, b) => a.file.localeCompare(b.file))) {
    md.push(`| \`${r.file}\` | ${r.tests} | ${r.passed} | ${r.failed} |`);
  }
  md.push("");
  writeFileSync(REPORT_MD_PATH, md.join("\n") + "\n");

  // ── BUILD_REPORT_HISTORY.json (append-only) ──────────────────────────────
  const historyEntry = {
    versionTag, commit, startedAt, finishedAt,
    totalFiles, totalTests, totalPassed, totalFailed,
    filesWithErrors: filesWithErrors.map(r => r.file),
  };
  const history = existsSync(HISTORY_JSON_PATH) ? JSON.parse(readFileSync(HISTORY_JSON_PATH, "utf-8")) : [];
  history.push(historyEntry);
  writeFileSync(HISTORY_JSON_PATH, JSON.stringify(history, null, 2) + "\n");

  console.log("\n" + "=".repeat(70));
  console.log(`TOTAL: ${totalTests} tests across ${totalFiles} files — ${totalPassed} passed, ${totalFailed} failed`);
  console.log(`Wrote ${REPORT_MD_PATH}`);
  console.log(`Appended to ${HISTORY_JSON_PATH} (${history.length} recorded run(s) total)`);
  console.log("=".repeat(70));

  if (totalFailed > 0 || filesWithErrors.length > 0) {
    process.exitCode = 1;
  }
}

main();
