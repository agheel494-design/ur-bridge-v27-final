// ─────────────────────────────────────────────────────────────────────────────
// UR Language — Layer C, Gate C-2: Grammar Staleness Check
// ─────────────────────────────────────────────────────────────────────────────
//
// Detects automatically when tools/grammar/keyword-contract.generated.json
// (the C-1 contract) has changed since extensions/vscode/syntaxes/
// ur.tmLanguage.json was last generated from it — per the explicit
// requirement that a stale generated grammar must be detectable, not
// merely prevented by convention (comments alone).

import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const CONTRACT_PATH = join(__dirname, "keyword-contract.generated.json");
const GRAMMAR_PATH = join(__dirname, "..", "..", "extensions", "vscode", "syntaxes", "ur.tmLanguage.json");

function main(): void {
  const contractRaw = readFileSync(CONTRACT_PATH, "utf-8");
  const currentContractHash = createHash("sha256").update(contractRaw).digest("hex");

  let grammar: { "x-ur-generator-metadata"?: { contractSha256?: string } };
  try {
    grammar = JSON.parse(readFileSync(GRAMMAR_PATH, "utf-8"));
  } catch (e) {
    console.error(`STALE: could not read/parse ${GRAMMAR_PATH} — has it been generated yet? (run generate-grammar.ts)`);
    process.exit(1);
  }

  const embeddedHash = grammar["x-ur-generator-metadata"]?.contractSha256;
  if (!embeddedHash) {
    console.error("STALE: generated grammar has no x-ur-generator-metadata.contractSha256 — was it generated by an older version of the generator, or hand-edited?");
    process.exit(1);
  }

  if (embeddedHash !== currentContractHash) {
    console.error("STALE: the contract has changed since this grammar was generated.");
    console.error(`  Embedded hash: ${embeddedHash}`);
    console.error(`  Current contract hash: ${currentContractHash}`);
    console.error("  Run: npx tsx tools/grammar/generate-grammar.ts");
    process.exit(1);
  }

  console.log("FRESH: generated grammar matches the current contract exactly.");
}

main();
